// `lexicon-builder prose-corpus`: data/corpus/prose-vi.txt for ENG-T20 (spec/01-engine.md 13.4):
// at least 200,000 syllables of legally safe Vietnamese text split into tokens.

import Foundation

enum ProseCorpus {
    /// Default size: comfortably above the 200,000 syllables ENG-T20 requires.
    static let defaultMinimumTokens = 250_000

    /// Takes one paragraph (line) from each legal text in turn, in SOURCES.tsv order, so that every
    /// document contributes, until `minimumTokens` tokens are collected. Each output line is one
    /// paragraph: its tokens (original case, Vietnamese letters only) separated by single spaces.
    static func generate(_ layout: Layout, minimumTokens: Int) throws -> String {
        try InputManifest.verify(layout)
        let sources = try LegalTexts.sources(layout)
        var documents: [[[String]]] = try sources.map { source in
            let text = try FileIO.readUTF8(LegalTexts.textFile(layout, id: source.id))
            return text.split(separator: "\n").map { VietnameseText.proseTokens(String($0)) }.filter { !$0.isEmpty }
        }
        let available = documents.reduce(0) { $0 + $1.reduce(0) { $0 + $1.count } }
        guard available >= minimumTokens else {
            throw BuilderError("legal texts hold \(available) tokens, fewer than the \(minimumTokens) requested")
        }
        var cursors = Array(repeating: 0, count: documents.count)
        var paragraphs: [String] = []
        var total = 0
        while total < minimumTokens {
            for index in documents.indices where cursors[index] < documents[index].count && total < minimumTokens {
                let tokens = documents[index][cursors[index]]
                cursors[index] += 1
                paragraphs.append(tokens.joined(separator: " "))
                total += tokens.count
            }
        }
        documents.removeAll()
        let header = [
            "# Vietnamese prose corpus for ENG-T20 (spec/01-engine.md 13.4). Generated by `lexicon-builder prose-corpus`; do not edit.",
            "# Source: Vietnamese legal normative documents listed in data/inputs/legal/SOURCES.tsv (not protected by copyright:",
            "# Law on Intellectual Property No. 50/2005/QH11, Article 15(2); see docs/decisions/0200-data-sources-and-licences.md).",
            "# Format: one paragraph per line, tokens separated by one space, original case. Lines starting with '#' are comments.",
            "# Tokens: \(total)",
        ]
        return joinedLines(header + paragraphs)
    }
}
