"""Generates Tests/VietnameseEngineTests/Corpus/layouts.tsv (QA-R4 category "layouts", spec/01-engine.md
section 2, REG-16).

The engine sees characters, never key codes. For each case (an intent: the characters a user means to type
in Telex or VNI) and each keyboard layout (US QWERTY, German QWERTZ, French AZERTY, US Dvorak, Colemak),
the generator finds the physical keys a user of that layout presses for those characters (US key positions,
with Shift or Option/AltGr), maps the physical keys back to characters through the same layout (the
character stream the host delivers), and writes one row per layout. The rows of a case must give identical
output: the `keys` column is the delivered stream and the `note` column records the physical keys as
`physical: ...` so the test can also show what a key-code-based engine would have typed (the QWERTZ y/z
confusion of REG-16).

Layout tables are the public, standard layouts (ANSI positions; the ISO key left of Z is `iso`).
Usage: python3 -I Scripts/generate-layout-corpus.py [--check]
"""

import argparse
import pathlib
import sys

# US key positions, by row, named by their US QWERTY unshifted character.
POSITIONS = list("`1234567890-=") + list("qwertyuiop[]\\") + list("asdfghjkl;'") + ["iso"] + list("zxcvbnm,./") + [" "]


def layout(rows_plain, rows_shift, altgr=None):
    """rows_*: the characters of each position in POSITIONS order (iso included); '\0' for none."""
    table = {}
    for position, plain, shifted in zip(POSITIONS, rows_plain, rows_shift):
        if plain != "\0":
            table.setdefault(plain, (position, ""))
        if shifted != "\0":
            table.setdefault(shifted, (position, "⇧"))
    for position, character in (altgr or {}).items():
        table.setdefault(character, (position, "⌥"))
    forward = {}
    for character, (position, modifier) in table.items():
        forward[(position, modifier)] = character
    return table, forward


def chars(text):
    return list(text)


LAYOUTS = {
    "qwerty": layout(
        chars("`1234567890-=qwertyuiop[]\\asdfghjkl;'\0zxcvbnm,./ "),
        chars("~!@#$%^&*()_+QWERTYUIOP{}|ASDFGHJKL:\"\0ZXCVBNM<>? "),
    ),
    "qwertz": layout(
        chars("^1234567890ß´qwertzuiopü+#asdfghjklöä<yxcvbnm,.- "),
        chars("°!\"§$%&/()=?`QWERTZUIOPÜ*'ASDFGHJKLÖÄ>YXCVBNM;:_ "),
        {"q": "@", "7": "{", "8": "[", "9": "]", "0": "}", "-": "\\", "]": "~", "iso": "|"},
    ),
    "azerty": layout(
        chars("²&é\"'(-è_çà)=azertyuiop^$*qsdfghjklmù<wxcvbn,;:! "),
        chars("\0" + "1234567890°+AZERTYUIOP¨£µQSDFGHJKLM%>WXCVBN?./§ "),
        {"2": "~", "3": "#", "4": "{", "5": "[", "6": "|", "7": "`", "8": "\\", "9": "^", "0": "@", "-": "]", "=": "}"},
    ),
    "dvorak": layout(
        chars("`1234567890[]',.pyfgcrl/=\\aoeuidhtns-\0;qjkxbmwvz "),
        chars("~!@#$%^&*(){}\"<>PYFGCRL?+|AOEUIDHTNS_\0:QJKXBMWVZ "),
    ),
    "colemak": layout(
        chars("`1234567890-=qwfpgjluy;[]\\arstdhneio'\0zxcvbkm,./ "),
        chars("~!@#$%^&*()_+QWFPGJLUY:{}|ARSTDHNEIO\"\0ZXCVBKM<>? "),
    ),
}

CASES = [
    ("TX01", "Telex", "vieejt nam ", "việt nam "),
    ("TX02", "Telex", "dduwowcj ", "được "),
    ("TX03", "Telex", "Tieengs Vieejt ", "Tiếng Việt "),
    ("TX04", "Telex", "zas dzaayj ", "zá dzậy "),
    ("TX05", "Telex", "traffic, wifi ", "traffic, wifi "),
    ("TX06", "Telex", "quz Quzhou ", "quz Quzhou "),
    ("TX07", "Telex", "khoong! yeeu ", "không! yêu "),
    ("TX08", "Telex", "xin chaof, tooi teen laf Kal. ", "xin chào, tôi tên là Kal. "),
    ("VN01", "VNI", "vie65t nam ", "việt nam "),
    ("VN02", "VNI", "d9uo7c5 ", "được "),
    ("VN03", "VNI", "ba6c3 ", "ba6c3 "),
    ("VN04", "VNI", "o@gmail.com ", "o@gmail.com "),
    ("VN05", "VNI", "(d9a6y la2 vi1 du5) ", "(đây là ví dụ) "),
]


def escape(text):
    return text.replace("\\", "\\\\").replace(" ", "\\s").replace("\t", "\\t").replace("\n", "\\n")


def physical_label(position, modifier):
    return modifier + ("␣" if position == " " else position)


def render():
    lines = [
        "# QA-R4 category \"layouts\" (spec/04-quality-release.md), GENERATED by Scripts/generate-layout-corpus.py:",
        "# do not edit by hand. Each case is typed on US QWERTY, German QWERTZ, French AZERTY, US Dvorak and",
        "# Colemak: the physical keys differ (note column, US key positions, ⇧ Shift, ⌥ Option/AltGr), the",
        "# characters the host delivers do not, and the output must be identical (spec/01-engine.md section 2,",
        "# REG-16: the engine never sees key codes). Resources: the 13.9 fixtures.",
        "# Columns: id, method, options, keys, expected (whole field), restore (- not checked), note.",
        "id\tmethod\toptions\tkeys\texpected\trestore\tnote",
    ]
    for case_id, method, intent, expected in CASES:
        for name, (table, forward) in LAYOUTS.items():
            physical = []
            for character in intent:
                if character not in table:
                    sys.exit(f"{name} cannot type {character!r} in {case_id}")
                physical.append(table[character])
            delivered = "".join(forward[key] for key in physical)
            assert delivered == intent, (name, case_id)
            labels = " ".join(physical_label(position, modifier) for position, modifier in physical)
            lines.append(
                f"LY-{case_id}-{name}\t{method}\t-\t{escape(delivered)}\t{escape(expected)}\t-\tphysical: {labels}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = pathlib.Path(__file__).resolve().parent.parent / "Tests/VietnameseEngineTests/Corpus/layouts.tsv"
    text = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print(f"{target} is out of date; run Scripts/generate-layout-corpus.py")
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
